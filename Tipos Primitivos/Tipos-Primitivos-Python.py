# Tipos primitivos do Python em código

numero = 10 #int(inteiro)
decimal = 2.5 #float(ponto flutuante)
nome = "Felipe" #str(string)
ativado = True #bool(booleano)

# Exemplos

print(numero * decimal) #saida será 25
print("meu nome é: ", nome) #saida será "meu nome é Felipe"
print("o botão está ativado? ", ativado) #saida será "True"